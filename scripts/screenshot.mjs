import {chromium} from '@playwright/test';
const browser=await chromium.launch({headless:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:960},deviceScaleFactor:1});
page.on('pageerror',e=>console.log('PAGE ERROR',e.message));
page.on('console',m=>{if(m.type()==='error')console.log('CONSOLE ERROR',m.text())});
await page.goto('http://127.0.0.1:5173');
await page.waitForSelector('.asset-grid img');
await page.screenshot({path:'tests/studio-desktop.png',fullPage:true});
console.log('TITLE',await page.title());
console.log('ASSETS',await page.locator('.asset-card').count());
console.log('FONTS',await page.evaluate(()=>document.fonts.check('700 20px Jakarta')));
await browser.close();
